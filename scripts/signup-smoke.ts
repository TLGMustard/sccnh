import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import type { AdminSnapshot, BrowserDashboard, PublicSnapshot } from '../lib/repository';

const origin = process.env.SIGNUP_TEST_ORIGIN ?? 'http://127.0.0.1:3117';
if (!['localhost', '127.0.0.1', '[::1]'].includes(new URL(origin).hostname)) throw new Error('This signup smoke test only runs on localhost with a disposable database.');
const adminCode = process.env.LOCAL_ORGANIZER_ACCESS_CODE ?? 'LocalOrganizer!2027';
const post = (path: string, value: object, cookie = '', requestOrigin = origin) => fetch(`${origin}${path}`, { method: 'POST', headers: { origin: requestOrigin, 'content-type': 'application/json', cookie }, body: JSON.stringify(value) });
const privateGet = (path: string, cookie = '') => fetch(`${origin}${path}`, { headers: { cookie }, cache: 'no-store' });
const cookieFrom = (response: Response) => response.headers.get('set-cookie')?.split(';')[0] ?? '';
const readMine = async (cookie = '') => (await (await privateGet('/api/signup', cookie)).json() as { dashboard: BrowserDashboard }).dashboard;
const identity = `smoke-${randomUUID()}@example.test`;
const profile = { firstName: 'Smoke', lastName: 'Volunteer', email: identity, phone: '3525550100', wantsSiteLead: true, consent: true };
const homepage = await fetch(origin);
assert.equal(homepage.status, 200);
const html = await homepage.text();
assert.match(html, /Bagel Day/);
assert.match(html, /Jan 28/);

const schedule = await (await fetch(`${origin}/api/site`)).json() as PublicSnapshot;
assert.equal(schedule.event.bagelDay, '2027-01-28');
const slots = schedule.shifts.filter((shift: { locationId: string; taskId: string; remaining: number }) => shift.locationId === 'plaza' && shift.taskId === 'tabling' && shift.remaining > 0);
assert.ok(slots.length >= 5);
const claim = { action: 'claim', ...profile, shiftIds: [slots[0].id, slots[1].id] };
assert.equal((await post('/api/signup', { ...claim, consent: false })).status, 400);
assert.equal((await post('/api/signup', claim, '', 'https://foreign.invalid')).status, 403);
assert.equal((await post('/api/signup', { ...claim, padding: 'x'.repeat(9000) })).status, 413);

const claimed = await post('/api/signup', claim);
assert.equal(claimed.status, 200, await claimed.text());
const cookie = cookieFrom(claimed);
assert.ok(cookie);
assert.match(claimed.headers.get('set-cookie') ?? '', /httponly/i);
assert.match(claimed.headers.get('set-cookie') ?? '', /samesite=strict/i);
const mine = await privateGet('/api/signup', cookie);
assert.match(mine.headers.get('cache-control') ?? '', /no-store/i);
const dashboard = (await mine.json() as { dashboard: BrowserDashboard }).dashboard;
assert.equal(dashboard.shifts.length, 2);
assert.equal(JSON.stringify(dashboard).includes(identity), false);
assert.equal((await readMine()).shifts.length, 0);
assert.equal((await post('/api/signup', { action: 'cancel', signupId: dashboard.shifts[0].signupId })).status, 401);
assert.equal((await post('/api/signup', { action: 'cancel', signupId: dashboard.shifts[0].signupId }, `sccnh_volunteer=${'a'.repeat(43)}`)).status, 404);

const separate = await post('/api/signup', { ...claim, shiftIds: [slots[2].id] });
assert.equal(separate.status, 200);
assert.equal((await readMine(cookieFrom(separate))).shifts.length, 1);
assert.equal((await privateGet('/api/admin/export')).status, 401);
assert.equal((await post('/api/admin/export', {})).status, 401);

const login = await post('/api/admin/session', { accessCode: adminCode });
assert.equal(login.status, 200, await login.text());
const adminCookie = cookieFrom(login);
const data = await (await privateGet('/api/admin', adminCookie)).json() as AdminSnapshot;
const volunteers = data.volunteers.filter((entry: { email: string }) => entry.email === identity);
assert.equal(volunteers.length, 2);
assert.equal(data.signups.filter((entry: { email: string }) => entry.email === identity).length, 3);
const csv = await privateGet('/api/admin/export', adminCookie);
assert.equal(csv.status, 200);
const contents = await csv.text();
assert.ok(contents.includes(identity));
assert.ok(contents.includes('2027-01-28'));
assert.doesNotMatch(contents, /access_code_hash|management_key|scrypt\$/);
assert.equal((await post('/api/admin/export', {}, adminCookie)).status, 503, 'Google export should report missing test-only configuration.');
const source = dashboard.shifts[0];
assert.equal((await post('/api/signup', { action: 'change', signupId: source.signupId, targetShiftId: slots[4].id }, cookie)).status, 200);
assert.equal((await post('/api/signup', { action: 'cancel', signupId: source.signupId }, cookie)).status, 200);
assert.equal((await readMine(cookie)).shifts.length, 1);
for (const volunteer of volunteers) assert.equal((await post('/api/admin', { action: 'delete-volunteer', volunteerId: volunteer.id, confirmAccessCode: adminCode }, adminCookie)).status, 200);
assert.equal((await readMine(cookie)).shifts.length, 0);
console.log('Local HTTP signup, privacy, organizer roster, CSV, change, cancellation, and cleanup checks passed.');
